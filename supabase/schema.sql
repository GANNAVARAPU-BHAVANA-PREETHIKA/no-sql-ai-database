create table if not exists nodes (
  node_id text primary key,
  capacity int not null check (capacity >= 0),
  used_storage int not null default 0 check (used_storage >= 0),
  speed text not null,
  status text not null default 'active' check (status in ('active', 'failed'))
);

create table if not exists shards (
  shard_id text primary key,
  node_id text not null references nodes(node_id) on delete cascade,
  size int not null check (size > 0)
);

create table if not exists replicas (
  id bigint generated by default as identity primary key,
  shard_id text not null references shards(shard_id) on delete cascade,
  node_id text not null references nodes(node_id) on delete cascade,
  type text not null check (type in ('primary', 'secondary'))
);

create table if not exists data_items (
  item_key text primary key,
  item_value text not null,
  size int not null check (size > 0),
  shard_id text not null unique references shards(shard_id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists system_config (
  id int primary key default 1 check (id = 1),
  consistency_mode text not null check (consistency_mode in ('STRONG', 'EVENTUAL', 'TUNABLE')),
  replication_factor int not null check (replication_factor > 0),
  read_quorum int not null check (read_quorum > 0),
  write_quorum int not null check (write_quorum > 0),
  updated_at timestamptz not null default now()
);

create table if not exists system_config_history (
  id bigint generated by default as identity primary key,
  consistency_mode text not null check (consistency_mode in ('STRONG', 'EVENTUAL', 'TUNABLE')),
  replication_factor int not null check (replication_factor > 0),
  read_quorum int not null check (read_quorum > 0),
  write_quorum int not null check (write_quorum > 0),
  changed_at timestamptz not null default now()
);

insert into system_config (id, consistency_mode, replication_factor, read_quorum, write_quorum)
values (1, 'TUNABLE', 3, 2, 2)
on conflict (id) do nothing;

create index if not exists idx_shards_node_id on shards(node_id);
create index if not exists idx_replicas_shard_id on replicas(shard_id);
create index if not exists idx_replicas_node_id on replicas(node_id);
create index if not exists idx_data_items_shard_id on data_items(shard_id);
create index if not exists idx_system_config_history_changed_at on system_config_history(changed_at desc);
